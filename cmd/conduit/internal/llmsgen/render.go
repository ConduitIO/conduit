// generatedHeader is the "do not edit by hand" marker every generated Go
// file in this repo carries in spirit (e.g. pkg/pipeline/status_string.go),
// adapted to a text file: an HTML comment renders invisibly wherever
// llms.txt is viewed as Markdown, but is still plainly visible as plain
// text.
const generatedHeader = "<!-- Code generated by cmd/conduit/internal/llmsgen; DO NOT EDIT. -->"

// summary is the one piece of hand-curated prose in either generated file
// (design doc's "File structure" section) — everything else is derived
// from the four sources.
const summary = "Broker-neutral data streaming engine and Kafka Connect replacement. Pipelines move " +
	"records from source connectors to destination connectors with processors in between; " +
	"any-language plugins over gRPC/WASM; embeddable; agent-legible with stable error codes and an " +
	"MCP server."

// generatedData bundles every source the generator reads, already gathered
// and sorted, so render{LLMS,LLMSFull}Txt are pure functions over plain
// data — the "formatter fixtures" golden tests in llmsgen_test.go feed
// these functions synthetic data without touching the real registries.
type generatedData struct {
	Connectors []connectorInfo
	ErrorCodes []errorCodeInfo
	MCPTools   []mcp.ToolInfo
	Config     configSchema
}

// readTools and writeTools split d.MCPTools by Mutates, each preserving
// the already-sorted-by-Name order of d.MCPTools.
func (d generatedData) readTools() []mcp.ToolInfo  { return filterTools(d.MCPTools, false) }
func (d generatedData) writeTools() []mcp.ToolInfo { return filterTools(d.MCPTools, true) }

func filterTools(tools []mcp.ToolInfo, mutates bool) []mcp.ToolInfo {
	var out []mcp.ToolInfo
	for _, t := range tools {
		if t.Mutates == mutates {
			out = append(out, t)
		}
	}
	return out
}

// sdkBatchSizeKey is the SDK source batching parameter whose default sourceBatchingNote reports.
const sdkBatchSizeKey = "sdk.batch.size"

// sourceBatchingNote states the default source batching (conduit-connector-sdk
// v0.18, design 20261027-default-source-batching.md) and its opt-out. The
// connector lists are derived from each connector's source sdk.batch.size
// default, so they cannot drift from the specs. It returns "" when no
// connector has the parameter.
func sourceBatchingNote(connectors []connectorInfo) string {
	var batched, off []string
	for _, c := range connectors {
		for _, p := range c.SourceParams {
			if p.Key != sdkBatchSizeKey {
				continue
			}
			if p.Default == "" || p.Default == "0" {
				off = append(off, c.Name)
			} else {
				batched = append(batched, fmt.Sprintf("%s (%s)", c.Name, p.Default))
			}
		}
	}
	if len(batched) == 0 && len(off) == 0 {
		return ""
	}
	note := "Source batching: a source that leaves `sdk.batch.size` and `sdk.batch.delay` unset reads in batches " +
		"(adaptive drain: it returns what is already queued, with no timer). Default sdk.batch.size of built-in sources: "
	note += strings.Join(batched, ", ")
	if len(off) > 0 {
		note += "; not batched by default: " + strings.Join(off, ", ")
	}
	return note + ". To read one record at a time, set both `sdk.batch.size: \"0\"` and `sdk.batch.delay: \"0\"` " +
		"on the source connector. Runbook: docs/operations/source-batching.md."
}

// destinationBatchingNote states how the preview engine batches a destination
// and what bounds the wait of a partial batch (#3231, #3321, design
// 20261103-archv2-destination-batch-timing.md).
const destinationBatchingNote = "Destination batching on `--preview.pipeline-arch-v2`: the engine batches a destination " +
	"itself with its effective `sdk.batch.size` and `sdk.batch.delay` (the pipeline config, else the connector's own " +
	"defaults, so S3 is batched at 1000 records / 1s with nothing set) and hands the connector `0` for them, so the " +
	"connector does not batch as well. It writes a partial batch at the latest `sdk.batch.delay` after its first record, " +
	"even when no further record arrives (a timer, as in the connector SDK). With `sdk.batch.size` alone a partial batch " +
	"waits for more records or a stop, and the start logs `pipeline.archv2_destination_batch_unbounded_wait`. A " +
	"dead-letter queue with `sdk.batch.size` above 1 or `sdk.batch.delay` above 0 is refused with " +
	"`pipeline.archv2_destination_batching_unsupported`. A destination or dead-letter-queue `sdk.batch.*` value " +
	"must be a literal: one containing `$` (an environment reference such as `${S3_BATCH}`) is refused with " +
	"`pipeline.archv2_destination_batching_not_literal`, because the engine batches with the value as written. " +
	"Runbook: docs/operations/archv2-destination-batching.md."

// renderLLMSTxt renders the concise, llmstxt.org-conformant index: one H1,
// one blockquote summary immediately after, then ## sections of links and
// counts. Every list here is derived from d; the full detail lives in
// llms-full.txt, which every section links to.
func renderLLMSTxt(d generatedData) string {
	var b strings.Builder

	b.WriteString(generatedHeader)
	b.WriteString("\n# Conduit\n\n")
	writeBlockquote(&b, summary)
	b.WriteString("\n")

	b.WriteString("## Pipeline configuration\n")
	fmt.Fprintf(&b, "- [Config schema (v2, latest %s)](llms-full.txt): version, pipelines, connectors, "+
		"processors, dead-letter-queue. Legacy v1 (%s) still parsed.\n\n", d.Config.LatestVersion, d.Config.LegacyVersion)

	b.WriteString("## Built-in connectors\n")
	for _, c := range d.Connectors {
		fmt.Fprintf(&b, "- %s — %s\n", c.Name, c.Summary)
	}
	fmt.Fprintf(&b, "(%d built-in connectors; full parameters in llms-full.txt)\n", len(d.Connectors))
	if note := sourceBatchingNote(d.Connectors); note != "" {
		b.WriteString("- " + note + "\n")
	}
	b.WriteString("- " + destinationBatchingNote + "\n")
	b.WriteString("\n")

	b.WriteString("## Error codes\n")
	fmt.Fprintf(&b, "- %d stable error codes, dotted `domain.name` reasons, each with a gRPC status "+
		"class. Full list with descriptions in llms-full.txt.\n", len(d.ErrorCodes))
	b.WriteString("- CLI `--json`: a failing command prints one JSON object on stdout whose `error` carries " +
		"`code`, `message`, `suggestion` and `configPath`; the exit code is 2 (validation), 3 (environment) " +
		"or 1 (runtime).\n\n")

	b.WriteString("## MCP tools\n")
	fmt.Fprintf(&b, "- Read: %s\n", joinToolNames(d.readTools()))
	fmt.Fprintf(&b, "- Write (require --allow-mutations): %s\n", joinToolNames(d.writeTools()))
	fmt.Fprintf(&b, "(%d tools; full schemas in llms-full.txt)\n\n", len(d.MCPTools))

	b.WriteString("## Deployment\n")
	b.WriteString("- [docker-compose quickstart](https://github.com/ConduitIO/conduit/tree/main/deploy/docker-compose): " +
		"`docker compose up -d --wait` starts a pinned, signed image with a running pipeline; state on a named volume.\n")
	b.WriteString("- [systemd, ECS and Nomad examples](https://github.com/ConduitIO/conduit/tree/main/deploy): " +
		"examples, not supported products. Set the stop timeout above 30 s so SIGTERM can drain; probes are " +
		"`/healthz` (liveness) and `/readyz` (readiness), both open without the API token.\n")
	b.WriteString("- [Ambient cloud credentials](https://github.com/ConduitIO/conduit/blob/main/docs/operations/ambient-credentials.md): " +
		"built-in connectors use the host's identity (for example the AWS default chain) only when the operator sets " +
		"`connectors.ambient-credentials.enabled=true` with exact `allow-resources`; a pipeline must name `builtin:s3`. " +
		"Off by default.\n")
	b.WriteString("- [Environment variables in settings](https://github.com/ConduitIO/conduit/blob/main/docs/operations/env-allowlist.md): " +
		"`${VAR}` in a connector or processor setting expands only for names the operator lists in `env.allow`; " +
		"otherwise `config.env_var_not_allowed`. Off by default; not settable over the API. " +
		"In a Go template inside a setting, write `$$x` for a literal `$x` (`{{ $$x := .Key }}`); a bare `$x` is read as a reference and refused. " +
		"A processor `condition` is not resolved, so it uses `$x` as written.\n")
	b.WriteString("- [Outbound HTTP from built-in processors](https://github.com/ConduitIO/conduit/blob/main/docs/operations/outbound-http-egress.md): " +
		"`webhook.http`, `ollama.request`, `openai.*` and `cohere.*` refuse private, loopback, link-local and metadata addresses " +
		"(`processor.egress_blocked`), on every redirect hop, and ignore proxy variables; the operator exempts exact destinations with " +
		"`processors.egress.builtin-allow`.\n")
	b.WriteString("- [Connector egress](https://github.com/ConduitIO/conduit/blob/main/docs/operations/connector-egress.md): " +
		"built-in connectors never connect to a cloud metadata endpoint (`connector.egress_blocked`); API writers are trusted to choose other targets, " +
		"and the operator can confine them with `connectors.egress.allow`.\n")
	b.WriteString("- [File access](https://github.com/ConduitIO/conduit/blob/main/docs/operations/file-access.md): " +
		"the `file` connector and `custom.javascript` (`script.path`, `require()`) are confined to the operator's " +
		"`connectors.file.allowed-dirs` and `processors.javascript.allowed-dirs` (`config.path_not_allowed`).\n\n")

	// Static, like Deployment: the suite lives in conduit-connector-sdk, not in
	// this module, so there is nothing here to derive it from.
	b.WriteString("## Building connectors\n")
	b.WriteString("- [Acceptance suite v2](https://conduitdata.io/docs/developing/connectors/acceptance-suite-v2): " +
		"`sdk.AcceptanceTestV2` (conduit-connector-sdk v0.16.0+, suite revision 2.0.0) is the bar for Conduit " +
		"Certified. Claims go in `AcceptanceCapabilities`; `CONDUIT_ACCEPTANCE_REPORT=<path>` writes a JSON report. " +
		"The report is evidence, not proof: until the registry re-runs the suite, Certified rests on maintainer " +
		"review and the registry check runs in warning mode. Throughput cases record records/s and fail only on a " +
		"stall or rejected record; they are not benchmarks.\n\n")

	b.WriteString("## Full detail\n")
	b.WriteString("- [llms-full.txt](llms-full.txt)\n")

	return b.String()
}

// renderLLMSFullTxt renders the expanded reference: the same header/H1/
// blockquote, then every source inlined in full.
func renderLLMSFullTxt(d generatedData) string {
	var b strings.Builder

	b.WriteString(generatedHeader)
	b.WriteString("\n# Conduit\n\n")
	writeBlockquote(&b, summary)
	b.WriteString("\n")

	renderConfigSchemaSection(&b, d.Config)
	renderConnectorsSection(&b, d.Connectors)
	renderErrorCodesSection(&b, d.ErrorCodes)
	renderMCPToolsSection(&b, d.MCPTools)

	return b.String()
}

// writeBlockquote wraps text to a fixed column width and writes it as a
// Markdown blockquote (each line prefixed "> "), matching the design doc's
// illustrative formatting. Wrapping is a pure function of the (constant)
// summary text, so it is as deterministic as the constant itself.
func writeBlockquote(b *strings.Builder, text string) {
	for _, line := range wrapText(text, 96) {
		b.WriteString("> ")
		b.WriteString(line)
		b.WriteString("\n")
	}
}

// wrapText greedily wraps text to width columns, breaking only on spaces.
func wrapText(text string, width int) []string {
	words := strings.Fields(text)
	if len(words) == 0 {
		return nil
	}

	var lines []string
	line := words[0]
	for _, w := range words[1:] {
		if len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w
			continue
		}
		line += " " + w
	}
	lines = append(lines, line)
	return lines
}

func joinToolNames(tools []mcp.ToolInfo) string {
	names := make([]string, len(tools))
	for i, t := range tools {
		names[i] = t.Name
	}
	return strings.Join(names, ", ")
}

func renderConfigSchemaSection(b *strings.Builder, cfg configSchema) {
	b.WriteString("## 1. Pipeline configuration schema\n\n")

	b.WriteString("### Versions\n")
	for _, v := range cfg.Versions {
		if v == cfg.LatestVersion {
			fmt.Fprintf(b, "- %s (latest)\n", v)
		} else {
			fmt.Fprintf(b, "- %s\n", v)
		}
	}
	b.WriteString("\n")

	for _, s := range cfg.Structs {
		fmt.Fprintf(b, "### %s\n\n", s.Name)
		b.WriteString("| Field | YAML key | Go type | Required |\n")
		b.WriteString("| --- | --- | --- | --- |\n")
		for _, f := range s.Fields {
			fmt.Fprintf(b, "| %s | `%s` | `%s` | %s |\n", f.GoField, f.YAMLKey, f.GoType, yesNo(f.Required))
		}
		b.WriteString("\n")
	}

	fmt.Fprintf(b, "### Legacy v1 (%s)\n\n", cfg.LegacyVersion)
	b.WriteString("v1 pipeline configs key `pipelines`, `connectors`, and `processors` by map (" +
		"`pipelines: {<id>: {...}}`) instead of v2's ordered list, so processor and connector ordering " +
		"within a v1 file is not deterministic. v1 has no `plugin`/`condition` processor fields and no " +
		"top-level `dead-letter-queue` before 1.1. New pipelines should use v2.\n\n")
}

// sanitizeConnectorDescription neutralizes ATX headings in a connector's
// Description so they cannot bleed into llms-full.txt's document outline as
// false sections — a connector README's "## How it works" must not read as a
// sibling of the generator's own "## 2. Built-in connectors". Heading lines
// outside fenced code blocks become bold text (the emphasis is kept, the outline
// entry is not); fenced blocks and their contents are left untouched.
func sanitizeConnectorDescription(desc string) string {
	lines := strings.Split(desc, "\n")
	inFence := false
	for i, line := range lines {
		trimmed := strings.TrimLeft(line, " \t")
		if strings.HasPrefix(trimmed, "```") || strings.HasPrefix(trimmed, "~~~") {
			inFence = !inFence
			continue
		}
		if inFence {
			continue
		}
		if bold, ok := atxHeadingToBold(trimmed); ok {
			lines[i] = bold
		}
	}
	return strings.Join(lines, "\n")
}

// atxHeadingToBold converts an ATX heading line ("## Title", optional trailing
// #) to bold ("**Title**"), returning ok=false when line is not an ATX heading.
func atxHeadingToBold(line string) (string, bool) {
	n := 0
	for n < len(line) && line[n] == '#' {
		n++
	}
	if n < 1 || n > 6 || n >= len(line) || line[n] != ' ' {
		return "", false
	}
	text := strings.TrimSpace(strings.TrimRight(strings.TrimSpace(line[n+1:]), "#"))
	if text == "" {
		return "", false
	}
	return "**" + text + "**", true
}

func renderConnectorsSection(b *strings.Builder, connectors []connectorInfo) {
	fmt.Fprintf(b, "## 2. Built-in connectors (%d)\n\n", len(connectors))
	if note := sourceBatchingNote(connectors); note != "" {
		b.WriteString(note + "\n\n")
	}
	b.WriteString(destinationBatchingNote + "\n\n")

	for _, c := range connectors {
		fmt.Fprintf(b, "### %s (%s)\n\n", c.Name, c.Version)
		fmt.Fprintf(b, "%s\n\n", c.Summary)
		if c.Description != "" {
			fmt.Fprintf(b, "%s\n\n", sanitizeConnectorDescription(c.Description))
		}
		fmt.Fprintf(b, "Author: %s\n\n", c.Author)

		b.WriteString("#### Source parameters\n\n")
		renderParamsTable(b, c.SourceParams)

		b.WriteString("#### Destination parameters\n\n")
		renderParamsTable(b, c.DestinationParams)
	}
}

func renderParamsTable(b *strings.Builder, params []paramInfo) {
	if len(params) == 0 {
		b.WriteString("(none)\n\n")
		return
	}

	b.WriteString("| Key | Type | Default | Required | Description | Validations |\n")
	b.WriteString("| --- | --- | --- | --- | --- | --- |\n")
	for _, p := range params {
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s |\n",
			escapeCell(p.Key), escapeCell(p.Type), escapeCell(p.Default), yesNo(p.Required),
			escapeCell(p.Description), escapeCell(strings.Join(p.Validations, ", ")))
	}
	b.WriteString("\n")
}

func renderErrorCodesSection(b *strings.Builder, codes []errorCodeInfo) {
	fmt.Fprintf(b, "## 3. Error codes (%d)\n\n", len(codes))

	b.WriteString("| Reason | gRPC status | Description |\n")
	b.WriteString("| --- | --- | --- |\n")
	for _, c := range codes {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", escapeCell(c.Reason), escapeCell(c.GRPCCode), escapeCell(c.Description))
	}
	b.WriteString("\n")
}

func renderMCPToolsSection(b *strings.Builder, tools []mcp.ToolInfo) {
	sorted := make([]mcp.ToolInfo, len(tools))
	copy(sorted, tools)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })

	fmt.Fprintf(b, "## 4. MCP tool catalog (%d)\n\n", len(sorted))

	b.WriteString("| Name | Class | Description |\n")
	b.WriteString("| --- | --- | --- |\n")
	for _, t := range sorted {
		class := "read"
		if t.Mutates {
			class = "write (requires --allow-mutations)"
		}
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", escapeCell(t.Name), class, escapeCell(t.Description))
	}
	b.WriteString("\n")
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}
	return "no"
}

// escapeCell makes s safe to embed as one Markdown table cell: newlines
// become spaces (a table cell cannot contain a literal line break) and
// pipe characters are escaped so they cannot be mistaken for a column
// separator.
func escapeCell(s string) string {
	s = strings.ReplaceAll(s, "\r\n", " ")
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "\\|")
	return strings.TrimSpace(s)
}
