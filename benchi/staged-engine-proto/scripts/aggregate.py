#!/usr/bin/env python3
"""aggregate.py DIR... : one markdown table over staged_session.py outputs.

Handles sessions with the optional fourth arm (v2-altA) and arms that produced
no records (shown as HANG). Output goes to stdout.
"""
import csv, json, os, statistics, sys

ARMS = ("v1", "v2-main", "v2-proto", "v2-altA")


def load(d):
    rows = list(csv.DictReader(open(os.path.join(d, "runs.csv"))))
    env = json.load(open(os.path.join(d, "env.json")))
    by = {}
    for r in rows:
        by.setdefault(r["arm"], {"a": {}, "b": {}})[r["rep"]][int(r["round"])] = int(r["rate"])
    return env, by


def fl(by, n):
    ds = []
    for r in by[n]["a"]:
        if r in by[n]["b"] and by[n]["a"][r] and by[n]["b"][r]:
            a, b = by[n]["a"][r], by[n]["b"][r]
            ds.append(abs(b - a) / ((a + b) / 2) * 100)
    return (statistics.median(ds), max(ds)) if ds else (float("nan"), float("nan"))


def med(by, n):
    v = [x for rep in ("a", "b") for x in by.get(n, {}).get(rep, {}).values() if x > 0]
    return statistics.median(v) if v else float("nan")


def main():
    dirs = sys.argv[1:]
    loaded = [(d,) + load(d) for d in dirs]
    has_alta = any("v2-altA" in by for _, _, by in loaded)
    arms = ARMS if has_alta else ARMS[:3]
    print("# Aggregate of the sessions\n")
    print("Generated by `scripts/aggregate.py`. Not gate evidence; see `README.md`. Each cell is the median rec/s per "
          "sink with the arm's own A/A floor (largest per-round difference between its two runs) in brackets.\n")
    head = "| session | shape and env | rounds x window | " + " | ".join(f"{a} (A/A max)" for a in arms) + " | proto vs v1 | proto vs v2-main | v2-main vs v1 |"
    if has_alta:
        head += " altA vs v2-main | proto vs altA |"
    print(head)
    print("| " + " | ".join(["---"] * (head.count("|") - 1)) + " |")
    for d, env, by in loaded:
        m = {n: med(by, n) for n in arms}
        f = {n: fl(by, n) if n in by else (float("nan"),) * 2 for n in arms}
        e = ", ".join(x.replace("CONDUIT_BENCH_", "") for x in env["env"])

        def c(n):
            if n not in by:
                return "-"
            return "HANG" if m[n] != m[n] else f"{m[n]:.0f} (+/-{f[n][1]:.1f}%)"

        def pct(x, y):
            if x not in by or y not in by:
                return "-"
            if m[x] != m[x] or m[y] != m[y]:
                return "n/a (hang)"
            return f"{(m[x]-m[y])/m[y]*100:+.1f}%"

        line = (f"| {os.path.basename(d.rstrip('/'))} | {env['shape']}{' ' + e if e else ''} | {env['rounds']} x {env['window']}s | "
                + " | ".join(c(n) for n in arms)
                + f" | {pct('v2-proto','v1')} | {pct('v2-proto','v2-main')} | {pct('v2-main','v1')} |")
        if has_alta:
            line += f" {pct('v2-altA','v2-main')} | {pct('v2-proto','v2-altA')} |"
        print(line)


main()
