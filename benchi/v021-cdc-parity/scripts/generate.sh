#!/usr/bin/env bash
# Regenerates the N-dependent benchmark artifacts from the environment:
#
#   TABLES               number of source tables / source+destination pairs
#                        (default 1; the benchmark sweeps 1, 2, 4)
#   CONDUIT_BATCH_SIZE   sdk.batch.size for each Conduit source (default 1000)
#   CONDUIT_BATCH_DELAY  sdk.batch.delay for each Conduit source (default 100ms)
#
# Emits (committed copies are the TABLES=1 default; run.sh regenerates them for
# the TABLES it was asked to run):
#
#   pipelines/conduit.yml  one pipeline per table: builtin:postgres source
#                          (bench_source_i, its own slot/publication) ->
#                          builtin:file sink (/sink/out_i.txt)
#   infra/init.sql         CREATE TABLE bench_source_0 .. bench_source_{N-1}
#   config/debezium-server.properties  one Debezium Engine capturing all N
#                          tables (one slot/publication) -> HTTP sink posting
#                          each event to the counter -> /sink/out.txt
#
# Boring and obvious on purpose: plain shell, no template engine, no branching
# beyond the loop over N. run.sh calls this before benchi so the artifacts match
# the TABLES it exports to docker compose.
set -euo pipefail
cd "$(dirname "$0")/.."

TABLES=${TABLES:-1}
CONDUIT_BATCH_SIZE=${CONDUIT_BATCH_SIZE:-1000}
CONDUIT_BATCH_DELAY=${CONDUIT_BATCH_DELAY:-100ms}

# Validate: TABLES and CONDUIT_BATCH_SIZE are positive integers, the delay is a
# non-empty duration string.
case "$TABLES" in
  ''|*[!0-9]*) echo "TABLES must be a positive integer (got '$TABLES')" >&2; exit 1 ;;
esac
if [ "$TABLES" -lt 1 ]; then echo "TABLES must be >= 1 (got '$TABLES')" >&2; exit 1; fi
case "$CONDUIT_BATCH_SIZE" in
  ''|*[!0-9]*) echo "CONDUIT_BATCH_SIZE must be a positive integer (got '$CONDUIT_BATCH_SIZE')" >&2; exit 1 ;;
esac
if [ "$CONDUIT_BATCH_SIZE" -lt 1 ]; then echo "CONDUIT_BATCH_SIZE must be >= 1" >&2; exit 1; fi
if [ -z "$CONDUIT_BATCH_DELAY" ]; then echo "CONDUIT_BATCH_DELAY must be non-empty" >&2; exit 1; fi

# -- infra/init.sql -----------------------------------------------------------
{
  echo "-- Source tables: one per benchmark table, every CDC arm captures all of"
  echo "-- them. The loader writes a fixed-rate INSERT/UPDATE/DELETE mix into each"
  echo "-- (see ../loader). Row shape is fixed (id bigint PRIMARY KEY, payload"
  echo "-- text) and identical across tables and arms."
  echo "--"
  echo "-- REPLICA IDENTITY stays DEFAULT (the primary key), so pgoutput emits the"
  echo "-- key for deletes and all three systems can reconstruct the changed row."
  echo "--"
  echo "-- GENERATED by scripts/generate.sh from TABLES (committed copy is the"
  echo "-- TABLES=1 default); run.sh regenerates it. Do not edit by hand."
  for ((i = 0; i < TABLES; i++)); do
    echo "CREATE TABLE bench_source_${i} ("
    echo "    id      bigint PRIMARY KEY,"
    echo "    payload text   NOT NULL"
    echo ");"
  done
} > infra/init.sql

# -- pipelines/conduit.yml ----------------------------------------------------
emit_pipeline() {
  local i=$1
  cat <<EOF
  - id: cdc-parity-${i}
    status: running
    name: cdc-parity-${i}
    description: >
      Postgres CDC source (bench_source_${i}, pgoutput/logrepl) -> file sink
      /sink/out_${i}.txt. Ground truth = lines written to /sink/out_${i}.txt
      (summed across tables).
    connectors:
      - id: cdc-parity-${i}:pg-src
        type: source
        plugin: builtin:postgres
        settings:
          url: "postgres://bench:bench@cdcparity-postgres:5432/bench?sslmode=disable"
          tables: "bench_source_${i}"
          cdcMode: "logrepl"
          snapshotMode: "never"
          logrepl.slotName: "conduit_slot_${i}"
          logrepl.publicationName: "conduit_pub_${i}"
          logrepl.autoCleanup: "false"
          logrepl.withAvroSchema: "false"
          sdk.batch.size: "${CONDUIT_BATCH_SIZE}"
          sdk.batch.delay: "${CONDUIT_BATCH_DELAY}"
      - id: cdc-parity-${i}:file-dest
        type: destination
        plugin: builtin:file
        settings:
          path: /sink/out_${i}.txt
EOF
}

{
  echo "# Conduit arm: one pipeline per table — builtin:postgres CDC source"
  echo "# (bench_source_i) -> builtin:file sink (/sink/out_i.txt)."
  echo "#"
  echo "# Ground truth is the files the sinks write: builtin:file appends exactly"
  echo "# one line per record (record.Bytes() + '\n'), so the sum of"
  echo "# \`wc -l /sink/out_*.txt\` is the number of CDC events actually delivered."
  echo "# No Conduit metric is read."
  echo "#"
  echo "# Equivalence notes (see ../README.md for the full list):"
  echo "#   - snapshotMode: never — no initial snapshot, matching Debezium"
  echo "#     snapshot.mode=never and Redpanda stream_snapshot:false."
  echo "#   - logrepl.withAvroSchema: false — raw JSON payload, matching Debezium's"
  echo "#     default and Redpanda's JSON message."
  echo "#   - cdcMode: logrepl — pgoutput logical replication, the same wire"
  echo "#     protocol Debezium (plugin.name=pgoutput) and Redpanda use."
  echo "#   - sdk.batch.size: CONDUIT_BATCH_SIZE (default 1000) with a small"
  echo "#     sdk.batch.delay so a partial batch still flushes; Debezium's"
  echo "#     max.batch.size defaults to 2048."
  echo "#"
  echo "# GENERATED by scripts/generate.sh from TABLES and CONDUIT_BATCH_SIZE"
  echo "# (committed copy is the TABLES=1 default); run.sh regenerates it."
  echo 'version: "2.2"'
  echo "pipelines:"
  for ((i = 0; i < TABLES; i++)); do
    emit_pipeline "$i"
  done
} > pipelines/conduit.yml

# -- config/debezium-server.properties -----------------------------------------
# One Debezium Engine (a single JVM, no Kafka broker / Connect worker) captures
# all TABLES tables over one replication slot + publication, then the built-in
# HTTP sink POSTs each change event to the counter service in
# tools/compose-debezium-server.yml, which writes one line per event to
# /sink/out.txt. The table list is N-dependent, so it is regenerated like the
# Conduit pipeline and init.sql.
tables_list="public.bench_source_0"
for ((i = 1; i < TABLES; i++)); do
  tables_list="${tables_list},public.bench_source_${i}"
done
cat > config/debezium-server.properties <<EOF
# Debezium Server (standalone) arm: the Debezium Engine as a single JVM process
# — no Kafka Connect worker, no Kafka broker. This is the apples-to-apples arm
# against Conduit's built-in CDC (both are single-process CDC pipelines).
#
# Source: the SAME Postgres source as every other arm — bench_source_0 ..
# bench_source_\${TABLES-1} over pgoutput logical replication, snapshot
# disabled (snapshot.mode=no_data — Debezium 3.4 renamed the old 'never'),
# so only the loader's steady-state stream is captured. One engine captures
# all tables with one replication slot / publication.
#
# Sink: the built-in HTTP sink POSTs each change event to the counter service
# in tools/compose-debezium-server.yml, which appends one line per event to
# /sink/out.txt. wc -l stays the ground-truth metric — no Debezium/engine
# metric is read. The HTTP hop is a documented non-equivalence (see README.md).
#
# GENERATED by scripts/generate.sh from TABLES (committed copy is the TABLES=1
# default); run.sh regenerates it. Do not edit by hand.

quarkus.log.level=ERROR
quarkus.log.console.json=false

debezium.sink.type=http
debezium.sink.http.url=http://cdcparity-debezium-counter:8080/

debezium.source.connector.class=io.debezium.connector.postgresql.PostgresConnector
debezium.source.offset.storage.file.filename=data/offsets.dat
debezium.source.offset.flush.interval.ms=0
debezium.source.database.hostname=cdcparity-postgres
debezium.source.database.port=5432
debezium.source.database.user=bench
debezium.source.database.password=bench
debezium.source.database.dbname=bench
debezium.source.topic.prefix=cdcparity
debezium.source.table.include.list=${tables_list}
debezium.source.plugin.name=pgoutput
debezium.source.slot.name=debezium_server_slot
debezium.source.publication.name=debezium_server_pub
debezium.source.publication.autocreate.mode=filtered
debezium.source.snapshot.mode=no_data
debezium.source.tombstones.on.delete=false
debezium.source.heartbeat.interval.ms=0
debezium.format.value=json
EOF

echo "generated: TABLES=$TABLES CONDUIT_BATCH_SIZE=$CONDUIT_BATCH_SIZE CONDUIT_BATCH_DELAY=$CONDUIT_BATCH_DELAY"
