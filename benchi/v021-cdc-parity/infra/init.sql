-- Source tables (bench_source_0 .. bench_source_{TABLES-1}) and
-- destination tables (bench_dest_0 .. bench_dest_{TABLES-1}), same row
-- shape. Every CDC arm captures the source tables; the Postgres-
-- destination arms (conduit-pg, connect-pg) write into the destination
-- tables, whose row count is their ground truth.
--
-- The loader writes a fixed-rate INSERT/UPDATE/DELETE mix into each
-- source table (see ../loader); it never touches the destination tables.
-- Row shape is fixed (id bigint PRIMARY KEY, payload text) and identical
-- across tables and arms. id stays PRIMARY KEY on the destination tables
-- too: the builtin:postgres destination and the JDBC sink both upsert on
-- the record key (id), which needs a unique constraint to target.
--
-- REPLICA IDENTITY stays DEFAULT (the primary key), so pgoutput emits the
-- key for deletes and all systems can reconstruct the changed row.
--
-- GENERATED by scripts/generate.sh from TABLES (committed copy is the
-- TABLES=1 default); run.sh regenerates it. Do not edit by hand.
CREATE TABLE bench_source_0 (
    id      bigint PRIMARY KEY,
    payload text   NOT NULL
);

CREATE TABLE bench_dest_0 (
    id      bigint PRIMARY KEY,
    payload text   NOT NULL
);
