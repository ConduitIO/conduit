#!/usr/bin/env python3
"""Prints the Dockerfile of the Conduit DIAG image: the repository Dockerfile,
unchanged except for its build step, which first adds
images/diag/pprof_benchdiag.go to cmd/conduit and adds `-tags benchdiag` to
the Makefile's own `go build` line (and builds the package instead of
main.go, so the extra file is compiled). Same base image, Go version, make
target, ldflags and -trimpath as the measured image (review R2-M3).

    diag-dockerfile.py REPO_DOCKERFILE REPO_MAKEFILE

Fails if either file no longer has the line it patches, so a changed build
cannot silently produce a differently built diag binary.
"""
import sys

BUILD = "RUN CGO_ENABLED=0 make build"
GO_BUILD = "go build -trimpath"
TARGET = "./cmd/conduit/main.go"


def main():
    dockerfile, makefile = open(sys.argv[1]).read(), open(sys.argv[2]).read()
    if dockerfile.count(BUILD) != 1:
        sys.exit(f"diag-dockerfile: '{BUILD}' not found exactly once in {sys.argv[1]}")
    build_line = next((l for l in makefile.splitlines() if GO_BUILD in l and TARGET in l), None)
    if build_line is None:
        sys.exit(f"diag-dockerfile: no '{GO_BUILD} ... {TARGET}' line in {sys.argv[2]}")
    patch = (
        "RUN cp benchi/v021-cdc-parity/matrix/images/diag/pprof_benchdiag.go cmd/conduit/ \\\n"
        f"    && sed -i 's#{GO_BUILD}#go build -tags benchdiag -trimpath#; s#{TARGET}#./cmd/conduit#' Makefile \\\n"
        "    && grep -q 'go build -tags benchdiag -trimpath' Makefile \\\n"
        "    && CGO_ENABLED=0 make build"
    )
    sys.stdout.write("# GENERATED by matrix/images/diag-dockerfile.py from the repository Dockerfile.\n"
                     + dockerfile.replace(BUILD, patch))


if __name__ == "__main__":
    main()
