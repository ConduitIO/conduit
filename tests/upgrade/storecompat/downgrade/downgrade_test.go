// Package downgrade is the downgrade half of the storage-engine gate.
//
// tests/upgrade/storecompat proves that a database written by the old
// libraries (v0.20.0: badger v4.9.1, sqlite v1.38.0) opens on the current
// ones. This module proves the reverse: a database written by the CURRENT
// libraries (badger v4.9.6, sqlite v1.46.1; fixtures testdata/badger-v4.9.6
// and testdata/sqlite-v1.46.1) opens and decodes with the OLD ones, so that
// rolling back from v0.20.1 to v0.20.0 keeps the data.
//
// It is a separate Go module because a single module cannot select both
// library versions: go.mod pins the old versions with replace directives
// and uses the repository's current code (replace => ../../../..) to read
// the state through the real stores. Run it with
//
//	cd tests/upgrade/storecompat/downgrade && go test -race ./...
//
// The fixtures are written by internal/gen with the current go.mod:
//
//	go run ./tests/upgrade/storecompat/internal/gen -type badger -out tests/upgrade/storecompat/testdata/badger-v4.9.6
//	go run ./tests/upgrade/storecompat/internal/gen -type sqlite -out tests/upgrade/storecompat/testdata/sqlite-v1.46.1
package downgrade

import (
	"context"
	"path/filepath"
	"testing"

	"github.com/conduitio/conduit-commons/database"
	"github.com/conduitio/conduit-commons/database/badger"
	"github.com/conduitio/conduit-commons/database/sqlite"
	"github.com/conduitio/conduit/pkg/connector"
	"github.com/conduitio/conduit/pkg/foundation/log"
	"github.com/conduitio/conduit/tests/upgrade/storecompat"
	"github.com/matryer/is"
	"github.com/rs/zerolog"
)

type fixture struct {
	dir string
	// writtenBy / readBy pin the library versions on each side, so a
	// fixture regenerated by the wrong build, or a module whose pins
	// drifted, fails loudly instead of testing nothing.
	module, writtenBy, readBy string
	open                      func(ctx context.Context, dir string) (database.DB, error)
}

var fixtures = []fixture{
	{
		dir:       "../testdata/badger-v4.9.6",
		module:    "github.com/dgraph-io/badger/v4",
		writtenBy: "v4.9.6",
		readBy:    "v4.9.1",
		open: func(_ context.Context, dir string) (database.DB, error) {
			return badger.New(zerolog.Nop(), filepath.Join(dir, "conduit.db"))
		},
	},
	{
		dir:       "../testdata/sqlite-v1.46.1",
		module:    "modernc.org/sqlite",
		writtenBy: "v1.46.1",
		readBy:    "v1.38.0",
		open: func(ctx context.Context, dir string) (database.DB, error) {
			return sqlite.New(ctx, zerolog.Nop(), filepath.Join(dir, "conduit.db"), storecompat.SQLiteTable)
		},
	},
}

// TestStoreCompat_NewFixtureReopensWithOldLibraries opens a database
// written by the current storage libraries using the v0.20.0 ones, checks
// every instance reads back exactly, then resumes (persists a newer source
// position, reopens, reads it back), as the upgrade test does.
func TestStoreCompat_NewFixtureReopensWithOldLibraries(t *testing.T) {
	for _, f := range fixtures {
		t.Run(filepath.Base(f.dir), func(t *testing.T) {
			is := is.New(t)
			ctx := context.Background()

			m, err := storecompat.ReadManifest(f.dir)
			is.NoErr(err)
			if got := m.Modules[f.module]; got != f.writtenBy {
				t.Fatalf("fixture %s was written by %s %s, want %s; regenerate it with the current go.mod", f.dir, f.module, got, f.writtenBy)
			}
			if got := storecompat.GoListVersion(ctx, f.module); got != f.readBy {
				t.Fatalf("this module reads with %s %s, want %s (v0.20.0's pin); fix the replace directives in go.mod", f.module, got, f.readBy)
			}
			t.Logf("fixture written by %s %s, reading with %s", f.module, f.writtenBy, f.readBy)

			dir := storecompat.CopyFixture(t, f.dir)
			db, err := f.open(ctx, dir)
			is.NoErr(err)
			storecompat.AssertState(t, ctx, db, storecompat.SourcePosition)

			conns := storecompat.ExpectedConnectors(storecompat.ResumedPosition)
			src := conns[storecompat.SourceID]
			is.NoErr(storecompat.PersistConnectors(ctx, db, log.Nop(), map[string]*connector.Instance{src.ID: src}))
			is.NoErr(db.Close())

			db, err = f.open(ctx, dir)
			is.NoErr(err)
			t.Cleanup(func() { _ = db.Close() })
			storecompat.AssertState(t, ctx, db, storecompat.ResumedPosition)
		})
	}
}
